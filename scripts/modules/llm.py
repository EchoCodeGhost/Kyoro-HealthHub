from __future__ import annotations

import base64
import contextlib
import io
import sys
import tempfile
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from health_config import Config
from modules.i18n import t
from utils.llm_provider import LLMProvider

_cfg = Config()
_text_provider_instance: LLMProvider | None = None
_vision_provider_instance: LLMProvider | None = None

# Angehängt an jeden System-Prompt (sofern nicht explizit abgewählt) — macht
# jede Aussage nachprüfbar statt nur plausibel klingend, siehe REAL-FM-
# Framework (Nature Biomedical Engineering, Aug 2026): Kalibrierung/
# Unsicherheitsangabe fehlte projektweit bis auf ein einzelnes Skript.
# Kurz gehalten, um die Antwortlänge nicht unnötig aufzublähen (längere
# Begründungsketten korrelieren laut Paper mit MEHR, nicht weniger Fehlern).
_GROUNDING_SUFFIX = (
    "\n\nFür jede zentrale Aussage: markiere kurz eine Konfidenz "
    "(hoch/mittel/niedrig) und nenne den konkreten Datenpunkt, auf dem sie "
    "beruht. Aussagen ohne Rückführung auf einen Datenpunkt explizit als "
    "eigene Einschätzung kennzeichnen, nicht als Tatsache formulieren."
    "\n\nFor each key statement: briefly mark a confidence level "
    "(high/medium/low) and name the concrete data point it's based on. "
    "Label statements that can't be traced to a data point as your own "
    "assessment, not as fact."
)

# openspec/specs/ethics-enforcement/spec.md, "Labeling of AI-generated
# output": SHALL be clearly labeled everywhere it is displayed. Applied by
# default at the return-value level here rather than per-caller, since a
# per-file audit found most analysis scripts producing unlabeled output
# despite the requirement (only health_query.py implemented it by hand).
_AI_LABEL_DE = "*KI-generiert von {model} am {ts} | Nicht für klinische Diagnose*"
_AI_LABEL_EN = "*AI-generated by {model} on {ts} | Not for clinical diagnosis*"


def grounding_suffix() -> str:
    """Public accessor for _GROUNDING_SUFFIX, for callers with their own LLM
    call path (e.g. health_query.py's ask_llm(), which talks to its provider
    directly instead of through call_llm()) that still want the calibration/
    grounding instruction applied."""
    return _GROUNDING_SUFFIX


def ai_label(provider_name: str | None = None) -> str:
    """Standard AI-generated disclaimer for any surface that displays LLM
    output outside call_llm()'s own label_output=True default (e.g. a
    caller with its own HTTP request instead of going through call_llm()).
    provider_name defaults to the configured text provider."""
    name = provider_name or _text_provider().name
    ts = datetime.now().strftime("%Y-%m-%d %H:%M")
    return t(_AI_LABEL_DE, _AI_LABEL_EN).format(model=name, ts=ts)


def _text_provider() -> LLMProvider:
    global _text_provider_instance
    if _text_provider_instance is None:
        _text_provider_instance = LLMProvider.from_config(_cfg._cfg)
    return _text_provider_instance


def _vision_provider() -> LLMProvider:
    global _vision_provider_instance
    if _vision_provider_instance is None:
        raw = _cfg._cfg
        if "vlm" in raw:
            _vision_provider_instance = LLMProvider.from_config({"llm": raw["vlm"]})
        else:
            _vision_provider_instance = LLMProvider.from_config(raw)
    return _vision_provider_instance


def call_llm(
    prompt: str,
    *,
    system: str | None = None,
    model: str | None = None,   # ignored — model comes from config
    image_b64: str | None = None,
    image_mime: str = "image/jpeg",
    max_tokens: int = 2000,
    temperature: float = 0.1,   # note: temperature is set per-provider in llm_provider.py
    require_grounding: bool = True,
    label_output: bool = True,
    caller: str | None = None,  # Name des aufrufenden Skripts (für Location-Filter)
) -> str:
    """Send a prompt to the configured LLM or VLM provider.

    require_grounding: appends _GROUNDING_SUFFIX to the system prompt
    (default True — most callers produce clinical claims that should be
    calibrated/traceable). Pass False for calls where confidence/source
    markers would be inappropriate (e.g. short structured/non-clinical
    outputs).

    label_output: appends ai_label() to the returned text (default True —
    openspec/specs/ethics-enforcement/spec.md requires LLM output be
    labeled as AI-generated wherever displayed). Pass False when the
    return value is parsed structurally instead of shown as prose (JSON
    extraction, regex-matched triage markers) — label at the point it is
    actually rendered to a person instead.

    caller: name of the calling script for the location filter
    (location_store.filter_prompt_text); defaults to the stem of sys.argv[0].
    For a remote provider (is_local false; unknown counts as remote) the
    prompt and system text pass through the filter and an image is
    re-encoded without metadata. If the image cannot be cleaned, nothing
    is sent.
    """
    from modules.location_store import filter_prompt_text, get_caller_name

    effective_caller = caller if caller is not None else get_caller_name()
    provider = _vision_provider() if image_b64 else _text_provider()
    is_remote = not getattr(provider, "is_local", False)

    if is_remote:
        prompt, _ = filter_prompt_text(prompt, effective_caller)
        if system:
            system, _ = filter_prompt_text(system, effective_caller)

    if require_grounding:
        system = (system or "") + _GROUNDING_SUFFIX

    if image_b64:
        image_data = base64.standard_b64decode(image_b64)
        if is_remote:
            image_data, image_mime = _strip_image_metadata(image_data, image_mime)
        ext = {"image/jpeg": ".jpg", "image/png": ".png",
               "image/webp": ".webp"}.get(image_mime, ".jpg")
        with tempfile.NamedTemporaryFile(suffix=ext, delete=False) as tmp:
            tmp.write(image_data)
            tmp_path = Path(tmp.name)
        try:
            text = provider.vision(tmp_path, prompt, max_tokens=max_tokens)
        finally:
            tmp_path.unlink(missing_ok=True)
        return text + "\n\n" + ai_label(provider.name) if label_output else text
    else:
        text = provider.chat(system or "", prompt, max_tokens=max_tokens)
        return text + "\n\n" + ai_label(provider.name) if label_output else text


class ImageMetadataError(RuntimeError):
    """Raised when an image cannot be re-encoded without metadata."""


def _strip_image_metadata(image_data: bytes, mime_type: str) -> tuple[bytes, str]:
    """Re-encode an image from its pixels only, dropping EXIF/XMP/GPS/ICC/text.

    The pixels are copied into a fresh image object, which carries no
    metadata; a palette is kept. Formats JPEG cannot hold (alpha, palette)
    are sent as PNG instead, so the returned MIME type may differ from the
    input. The result is re-opened and checked for leftover EXIF.

    Fails closed: on any error ImageMetadataError is raised and the caller
    must not send the image. Returns (clean bytes, MIME type).
    """
    from PIL import Image

    try:
        with Image.open(io.BytesIO(image_data)) as img:
            img.load()
            clean = Image.frombytes(img.mode, img.size, img.tobytes())
            if img.mode == "P" and img.getpalette():
                clean.putpalette(img.getpalette())

        out_mime = mime_type if mime_type in ("image/png", "image/webp") else "image/jpeg"
        if out_mime == "image/jpeg" and clean.mode not in ("RGB", "L", "CMYK"):
            out_mime = "image/png"
        fmt = {"image/png": "PNG", "image/webp": "WEBP", "image/jpeg": "JPEG"}[out_mime]

        buf = io.BytesIO()
        if fmt == "JPEG":
            clean.save(buf, format=fmt, quality=95)
        else:
            clean.save(buf, format=fmt)
        cleaned = buf.getvalue()

        with Image.open(io.BytesIO(cleaned)) as check:
            if len(check.getexif()) or "xmp" in check.info or "icc_profile" in check.info:
                raise ImageMetadataError("metadata survived re-encoding")
        return cleaned, out_mime
    except ImageMetadataError:
        raise
    except Exception as e:
        raise ImageMetadataError(
            t(f"Bild konnte nicht ohne Metadaten neu kodiert werden, wird nicht gesendet: {e}",
              f"Image could not be re-encoded without metadata, not sending it: {e}")
        ) from e


class _Tee(io.TextIOBase):
    def __init__(self, real):
        self.real = real
        self.buf = io.StringIO()

    def write(self, s):
        self.buf.write(s)
        return self.real.write(s)

    def flush(self):
        self.real.flush()


@contextlib.contextmanager
def capture_stdout():
    """Context manager for console-only scripts (documented @writes: stdout only)
    that still want an LLM commentary: everything printed inside the `with` block
    keeps appearing live on the terminal AND is captured, so it can be handed to
    call_llm() as the report text afterwards. Replaces a _Tee class that used to
    be duplicated verbatim in analyse_product_exposures.py and analyse_allergens.py.

    Usage:
        with capture_stdout() as buf:
            report_summary(conn, person)
            report_daily(conn, person)
        llm_text = call_llm(buf.getvalue(), system=SYSTEM_PROMPT)
    """
    tee = _Tee(sys.stdout)
    old_stdout = sys.stdout
    sys.stdout = tee
    try:
        yield tee.buf
    finally:
        sys.stdout = old_stdout
